    P = Polygon(q); c = P.centroid; r = list(P.minimum_rotated_rectangle.exterior.coords)
    e = max([(r[i], r[i + 1]) for i in range(2)], key=lambda s: math.dist(*s))
    d['parkCars'].append([round(c.x, 2), round(c.y, 2), round(math.atan2(e[1][0] - e[0][0], e[1][1] - e[0][1]), 3)])
