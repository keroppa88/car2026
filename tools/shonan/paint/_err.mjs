import { startServer, openCourse } from '../../../test/lib/harness.mjs';
const s = await startServer();
let errs = [];
const { browser, page } = await openCourse(s, { course: 'shonan', onPage: (p) => { p.on('pageerror', (e) => errs.push('PE ' + e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push('CE ' + m.text()); }); } }).catch((e) => { console.log('open fail', e.message); process.exit(1); });
page.on('pageerror', (e) => errs.push('PE ' + e.message));
page.on('console', (m) => { if (m.type() === 'error' || /error|Error/.test(m.text())) errs.push('C ' + m.text()); });
await page.waitForTimeout(4000);
console.log(errs.slice(0, 20).join('\n'));
console.log(await page.evaluate(() => document.getElementById('osm-loading-step')?.textContent + ' | ' + document.body.dataset.mapSource));
await browser.close(); process.exit(0);
